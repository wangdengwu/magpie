// transFor is a language's translator, English's list always in hand as the
// fallback.
func transFor(l lang) trans {
	if l == langEN {
		return trans{lang: langEN, own: enWords, en: enWords}
	}
	return trans{lang: l, own: wordList(l), en: enWords}
}

// wordList is a language's own sentences.
func wordList(l lang) words {
	switch l {
	case langZH:
		return zhWords
	}
	return enWords
}
